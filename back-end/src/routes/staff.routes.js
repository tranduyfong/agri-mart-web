const express = require('express');
const controller = require('../controllers/staff.controllers');
const productController = require('../controllers/product.controllers');
const categoryController = require('../controllers/category.controllers');
const { verifyToken, verifyAdminOrStaff } = require('../middlewares/auth.middleware');
const { loadStaffContext } = require('../middlewares/staff.middleware');
const { requirePermission } = require('../middlewares/permission.middleware');
const { uploadImages } = require('../middlewares/upload.middleware');
const router = express.Router();

router.use(verifyToken, verifyAdminOrStaff, loadStaffContext);
router.get('/session', controller.getSession);
router.get('/lookups', controller.getLookups);
router.get('/dashboard', controller.getDashboard);
router.get('/products', requirePermission('PRODUCT_MANAGE'), productController.getManageProducts);
router.get('/products/:id', requirePermission('PRODUCT_MANAGE'), productController.getManageProductDetail);
router.post('/products', requirePermission('PRODUCT_MANAGE'), uploadImages, productController.addProduct);
router.put('/products/:id', requirePermission('PRODUCT_MANAGE'), uploadImages, productController.updateProduct);
router.get('/categories', requirePermission('PRODUCT_MANAGE'), categoryController.getCategories);
router.post('/categories', requirePermission('PRODUCT_MANAGE'), uploadImages, controller.saveCategory);
router.put('/categories/:id', requirePermission('PRODUCT_MANAGE'), uploadImages, controller.saveCategory);
router.get('/inventory', requirePermission('INVENTORY_MANAGE'), controller.getInventory);
router.post('/imports/preview', requirePermission('INVENTORY_MANAGE'), controller.previewImport);
router.post('/imports', requirePermission('INVENTORY_MANAGE'), controller.confirmImport);
router.get('/imports/:id', requirePermission('INVENTORY_MANAGE'), controller.getReceipt);
router.get('/orders', requirePermission('ORDER_MANAGE'), controller.getOrders);
router.get('/orders/summary', requirePermission('ORDER_MANAGE'), controller.getOrderSummary);
router.get('/orders/:id', requirePermission('ORDER_MANAGE'), controller.getOrder);
router.patch('/orders/:id/status', requirePermission('ORDER_MANAGE'), controller.updateOrderStatus);
router.get('/promotions', requirePermission('PROMOTION_MANAGE'), controller.getPromotions);
router.get('/promotions/:id', requirePermission('PROMOTION_MANAGE'), controller.getPromotion);
router.post('/promotions', requirePermission('PROMOTION_MANAGE'), uploadImages, controller.savePromotion);
router.put('/promotions/:id', requirePermission('PROMOTION_MANAGE'), uploadImages, controller.savePromotion);
router.patch('/promotions/:id/end', requirePermission('PROMOTION_MANAGE'), controller.endPromotion);
router.get('/banners', requirePermission('BANNER_MANAGE'), controller.getBanners);
router.get('/banners/:id', requirePermission('BANNER_MANAGE'), controller.getBanner);
router.post('/banners', requirePermission('BANNER_MANAGE'), uploadImages, controller.saveBanner);
router.put('/banners/:id', requirePermission('BANNER_MANAGE'), uploadImages, controller.saveBanner);
router.get('/newsletters', requirePermission('NEWSLETTER_MANAGE'), controller.getNewsletters);
router.get('/newsletters/:id', requirePermission('NEWSLETTER_MANAGE'), controller.getNewsletter);
router.post('/newsletters', requirePermission('NEWSLETTER_MANAGE'), controller.saveNewsletter);
router.put('/newsletters/:id', requirePermission('NEWSLETTER_MANAGE'), controller.saveNewsletter);
router.post('/newsletters/:id/send', requirePermission('NEWSLETTER_MANAGE'), controller.sendNewsletter);
router.get('/support', requirePermission('SUPPORT_MANAGE'), controller.getRooms);
router.get('/support/:id', requirePermission('SUPPORT_MANAGE'), controller.getRoom);
router.post('/support/:id/claim', requirePermission('SUPPORT_MANAGE'), controller.claimRoom);
router.post('/support/:id/messages', requirePermission('SUPPORT_MANAGE'), uploadImages, controller.reply);
router.post('/support/:id/close', requirePermission('SUPPORT_MANAGE'), controller.closeRoom);

module.exports = router;
